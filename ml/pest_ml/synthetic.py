"""Deterministic generator for the committed synthetic fixture.

No real images, farms, people or field measurements are involved. Every value
is derived from SHA-256 of a fixed string, so the fixture is byte-identical on
any machine and any Python version. The fixture exists to exercise the
pipeline; it must never be described as a dataset or a model result.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

FIXTURE_SEED = "synthetic-fixture-v1"
GROUPS_PER_CLASS = 10
IMAGES_PER_GROUP = 3
FEATURE_DIM = 4
NOISE = 0.75
CREATED_AT = "2026-11-06T00:00:00Z"

# label, display name, class centre in the four-dimensional fixture space
# Centres deliberately overlap so the fixture exercises errors, not a perfect score.
CLASSES = (
    ("lesion_like", "synthetic lesion-like pattern", (0.6, 0.3, 0.1, 0.0)),
    ("healthy_like", "synthetic healthy-like pattern", (0.1, 0.6, 0.3, 0.0)),
    ("other_like", "synthetic other pattern", (0.3, 0.1, 0.6, 0.0)),
)


def _noise(*parts: str) -> list[float]:
    digest = hashlib.sha256("|".join(parts).encode("utf-8")).digest()
    values: list[float] = []
    for index in range(FEATURE_DIM):
        chunk = digest[index * 4 : (index + 1) * 4]
        fraction = int.from_bytes(chunk, "big") / (2**32)
        values.append((fraction * 2.0 - 1.0) * NOISE)
    return values


def build_dataset() -> tuple[str, str]:
    """Return ``(jsonl_text, manifest_text)`` for the synthetic fixture."""

    lines: list[str] = []
    for label, _display_name, centre in CLASSES:
        for group_index in range(GROUPS_PER_CLASS):
            group_id = f"synthetic-{label}-g{group_index:02d}"
            for image_index in range(IMAGES_PER_GROUP):
                image_id = f"{group_id}-i{image_index:02d}"
                noise = _noise(FIXTURE_SEED, group_id, str(image_index))
                features = [
                    round(centre[dimension] + noise[dimension], 6)
                    for dimension in range(FEATURE_DIM)
                ]
                record = {
                    "image_id": image_id,
                    "group_id": group_id,
                    "label": label,
                    "features": features,
                    "is_demo": True,
                    "synthetic": True,
                }
                lines.append(json.dumps(record, sort_keys=True, separators=(",", ":")))

    data_text = "\n".join(lines) + "\n"
    data_sha256 = hashlib.sha256(data_text.encode("utf-8")).hexdigest()
    manifest = {
        "schema_version": "1.0",
        "dataset_id": "synthetic-image-triage-fixture-v1",
        "description": (
            "Deterministically generated feature vectors for pipeline tests. "
            "No real images, farms, people or field measurements."
        ),
        "fixture_kind": "synthetic_fixture",
        "is_demo": True,
        "created_at": CREATED_AT,
        "licence": "CC0-1.0",
        "provenance": (f"generated by ml/pest_ml/synthetic.py; seed={FIXTURE_SEED}; no real data"),
        "feature_contract_version": "synthetic-features-v1",
        "feature_dim": FEATURE_DIM,
        "taxonomy_version": "synthetic-taxonomy-1",
        "classes": [
            {"label": label, "display_name": display_name}
            for label, display_name, _centre in CLASSES
        ],
        "data_file": "synthetic_dataset.jsonl",
        "data_sha256": data_sha256,
        "items_count": len(lines),
        "permissions": {
            "consent_ref": "not_applicable_synthetic",
            "ethics_ref": "not_applicable_synthetic",
            "data_owner": "PS-03 project",
            "personal_data": False,
        },
    }
    manifest_text = json.dumps(manifest, indent=2, sort_keys=True) + "\n"
    return data_text, manifest_text


def write_dataset(directory: str | Path) -> tuple[Path, Path]:
    """Write the fixture files into ``directory`` and return their paths."""

    target = Path(directory)
    target.mkdir(parents=True, exist_ok=True)
    data_text, manifest_text = build_dataset()
    data_path = target / "synthetic_dataset.jsonl"
    manifest_path = target / "synthetic_manifest.json"
    data_path.write_text(data_text, encoding="utf-8", newline="")
    manifest_path.write_text(manifest_text, encoding="utf-8", newline="")
    return data_path, manifest_path


if __name__ == "__main__":
    written = write_dataset(Path(__file__).resolve().parents[1] / "fixtures")
    for path in written:
        print(path)
