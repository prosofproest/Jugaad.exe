"""Media (image) API router.
Provides a signed upload endpoint and basic validation.
For now the implementation is a stub – it stores a record in the DB and returns a dummy signed URL.
"""

from fastapi import APIRouter, Depends, File, HTTPException, UploadFile, status
from sqlalchemy.orm import Session

from backend.app.database import get_db
from backend.app.models import Image, Observation
from backend.app.permissions import get_current_user, require_roles, Role

router = APIRouter()

def _validate_image(file: UploadFile) -> None:
    """Very light validation – check MIME and size limit (5 MB)."""
    if not file.content_type.startswith("image/"):
        raise HTTPException(status_code=status.HTTP_400_BAD_REQUEST, detail="File must be an image")
    # In a real implementation we would read the stream to enforce size.
    # Here we trust the client for the stub.

@router.post("/upload", summary="Signed image upload (stub)")
async def upload_image(
    observation_id: int,
    file: UploadFile = File(...),
    db: Session = Depends(get_db),
    user: dict = Depends(get_current_user),
    _: dict = Depends(require_roles([Role.farmer, Role.extension_worker, Role.admin])),
):
    # Basic checks
    _validate_image(file)
    # Ensure observation belongs to the user (owner check)
    obs = db.query(Observation).filter(Observation.id == observation_id).first()
    if not obs:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Observation not found")
    if obs.user_id != int(user.get("id", -1)) and user["role"] != Role.admin.value:
        raise HTTPException(status_code=status.HTTP_403_FORBIDDEN, detail="Not authorized for this observation")
    # Store a placeholder Image record
    image = Image(
        observation_id=observation_id,
        public_id=f"dummy_{observation_id}_{file.filename}",
        url=f"https://example.cloudinary.com/{file.filename}",
    )
    db.add(image)
    db.commit()
    db.refresh(image)
    # Return a stub signed URL (in reality would be generated by Cloudinary)
    signed_url = f"{image.url}?signature=stub&expires=9999999999"
    return {"image_id": image.id, "signed_url": signed_url}

